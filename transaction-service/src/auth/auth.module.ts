import { Global, Module } from '@nestjs/common';
import { JwtModule } from '@nestjs/jwt';
import * as fs from 'fs';
import * as path from 'path';
import { JwtAuthGuard } from './guards/jwt-auth.guard';
import { PermissionsGuard } from './guards/permissions.guard';

/**
 * Tokens are minted by auth-service with RS256. This service only needs the
 * public key to verify them, so it never signs anything. Defaults to the
 * sibling checkout's key so `nx run` works out of the box in the monorepo.
 */
function readPublicKey(): string {
  const file = process.env.JWT_PUBLIC_KEY_PATH
    ? path.resolve(process.env.JWT_PUBLIC_KEY_PATH)
    : path.join(process.cwd(), '..', 'auth-service', 'keys', 'public.pem');
  if (!fs.existsSync(file)) {
    throw new Error(
      `JWT public key not found at ${file}. Set JWT_PUBLIC_KEY_PATH to the ` +
        `public.pem generated by auth-service ("npm run keys:generate" there).`,
    );
  }
  return fs.readFileSync(file, 'utf8');
}

@Global()
@Module({
  imports: [
    JwtModule.register({
      publicKey: readPublicKey(),
      verifyOptions: { algorithms: ['RS256'] },
    }),
  ],
  providers: [JwtAuthGuard, PermissionsGuard],
  exports: [JwtModule, JwtAuthGuard, PermissionsGuard],
})
export class AuthModule {}
